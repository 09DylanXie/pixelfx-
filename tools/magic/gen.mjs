// Write the 3000 magic effects into a pixelfx checkout as ordinary effect files, add the 25 categories,
// regenerate src/fx/index.js (same format as the repo's tools/index.mjs) and write docs/MAGIC.md.
//   node tools/magic/gen.mjs <repo> [school,school]
import { writeFileSync, mkdirSync, readFileSync, readdirSync, statSync, rmSync, existsSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const repo = process.argv[2], only = process.argv[3] ? process.argv[3].split(",") : null; // optional: regenerate just these schools
const FX = join(repo, "src/fx");
const magic = await import(pathToFileURL(join(FX, "_magic/index.js")).href);
const { SCHOOLS, ARCHETYPES, VARIANTS, idFor, make } = magic;

const core = await import(pathToFileURL(join(repo, "src/core/index.js")).href);

// Render an effect on a big canvas and measure it: the box every color pixel and every visible bit of
// glow lands in, and (for one-shots) the time after which nothing is drawn any more.
function measure(mod) {
  const m = mod.meta, [w, h] = m.size, [ox, oy] = m.origin, MG = 240;
  const f = core.createFrame(w + MG * 2, h + MG * 2, -MG, -MG), inst = core.createFx(mod, { x: ox, y: oy });
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity, lastLit = 0;
  const steps = Math.round(m.duration * 30 * (m.loop ? 1 : 3)) + 1;
  for (let i = 0; i < steps; i++) {
    core.clearFrame(f); inst.draw(f);
    let any = false;
    for (let y = 0; y < f.h; y++) for (let x = 0; x < f.w; x++) {
      const k = y * f.w + x, l = f.light[k], c = f.color[k] >>> 24;
      const lv = Math.max(l & 255, (l >>> 8) & 255, (l >>> 16) & 255), glow = lv > 14;
      if (c || lv > 0) any = true; // any trace at all keeps the effect alive
      if (!c && !glow) continue;
      if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y;
    }
    if (any) lastLit = i;
    inst.update(1 / 30);
  }
  // back to effect space, padded by 2 px and rounded out to whole 4 px
  const pad = 2, L = Math.floor((x0 - MG - pad) / 4) * 4, T = Math.floor((y0 - MG - pad) / 4) * 4;
  const R = Math.ceil((x1 - MG + 1 + pad) / 4) * 4, B = Math.ceil((y1 - MG + 1 + pad) / 4) * 4;
  return {
    size: [R - L, B - T],
    origin: [ox - L, oy - T],
    duration: m.loop ? undefined : Math.ceil(((lastLit + 1) / 30 + 0.05) * 20) / 20,
  };
}

// 1. the effect files: two lines each, carrying the measured fit
let n = 0;
for (const S of SCHOOLS) {
  if (only && !only.includes(S.id)) { n += ARCHETYPES.length * VARIANTS.length; continue; }
  const dir = join(FX, `magic-${S.id}`);
  if (existsSync(dir)) rmSync(dir, { recursive: true });
  mkdirSync(dir, { recursive: true });
  for (const A of ARCHETYPES)
    VARIANTS.forEach((V, vi) => {
      const id = idFor(S.id, A.id, vi), file = join(FX, id + ".js");
      const mod = make(S.id, A.id, vi), m = mod.meta, fit = measure(mod);
      writeFileSync(file,
        `// ${m.name}: generated by the magic generator (src/fx/_magic). Edit the archetype "${A.id}" or the school "${S.id}" there, not this file.\n` +
        `// The fit (canvas, origin, length) was measured from a render; regenerate after changing the generator.\n` +
        `import { make } from "../_magic/index.js";\n` +
        `export const { meta, create, draw, drawBack } = make("${S.id}", "${A.id}", ${vi}, ${JSON.stringify(fit)});\n`);
      n++;
    });
}

// 2. categories: one per school, after the originals
const catFile = join(FX, "categories.js");
let cats = readFileSync(catFile, "utf8").replace(/\n  \/\/ magic-generated[\s\S]*?\/\/ end magic\n/, "\n");
const lines = SCHOOLS.map((S) => `  { id: "magic-${S.id}", name: "${S.name.toLowerCase()} magic", blurb: "${S.adj} spells of ${S.matter}, ${ARCHETYPES.length} kinds in 5 forms each" },`);
cats = cats.replace(/\n\];\s*$/, `\n  // magic-generated\n${lines.join("\n")}\n  // end magic\n];\n`);
writeFileSync(catFile, cats);

// 3. the registry, in the repo's own format and order
const { categories } = await import(pathToFileURL(catFile).href + "?v=" + Date.now());
const ids = [];
for (const cat of readdirSync(FX).sort()) {
  const d = join(FX, cat);
  if (cat.startsWith("_") || !statSync(d).isDirectory()) continue;
  for (const f of readdirSync(d).sort()) if (f.endsWith(".js") && !f.startsWith("_")) ids.push(`${cat}/${f.slice(0, -3)}`);
}
const order = new Map(categories.map((c, i) => [c.id, i]));
const rank = (id) => order.get(id.split("/")[0]) ?? 99;
ids.sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
const ident = (id) => id.replace(/[^a-z0-9]+/gi, "_");
writeFileSync(join(FX, "index.js"), [
  "// Generated by tools/index.mjs: every effect, by id. Don't edit; run `node tools/index.mjs`.",
  "",
  ...ids.map((id) => `import * as ${ident(id)} from "./${id}.js";`),
  "",
  `export { categories } from "./categories.js";`,
  "",
  "export const effects = {",
  ...ids.map((id) => `  "${id}": ${ident(id)},`),
  "};",
  "",
].join("\n"));

// 4. a catalog of the magic
const md = ["# Magic", "", `${n} generated spell effects: ${SCHOOLS.length} schools × ${ARCHETYPES.length} archetypes × ${VARIANTS.length} forms.`,
  "Each file in `src/fx/magic-<school>/` is two lines that call the generator in `src/fx/_magic/`; change an archetype or a school there and all its effects change with it.", "",
  "Forms: **standard**, **lesser** (smaller, quicker), **greater** (bigger, denser), **wild** (twice the particles, more chaos), **ancient** (slower, an extra ring or glyph).", "",
  "## Schools", "", "| school | palette | particles | debris | volume | motion | glyphs |", "|---|---|---|---|---|---|---|",
  ...SCHOOLS.map((S) => `| ${S.name} | ${S.palette.map((c) => "`" + c + "`").join(" ")} | ${S.spark} | ${S.bit ?? "—"} | ${S.puff ?? "—"} | ${S.flow} | ${S.glyph} |`), "",
  "## Archetypes", "", "| archetype | id suffix | | size (standard) | what it does (blood) |", "|---|---|---|---|---|",
  ...ARCHETYPES.map((A) => `| ${A.name} | \`-${A.id}\` | ${A.loop ? "loop" : "one-shot"} ${A.duration}s | ${A.size[0]}×${A.size[1]} | ${A.desc(SCHOOLS[0])} |`), "",
  "Ids look like `magic-<school>/<school>-<archetype>[-<form>]`, e.g. `magic-frost/frost-nova-greater`.", ""];
writeFileSync(join(repo, "docs/MAGIC.md"), md.join("\n"));
console.log(`${n} magic effects written; registry has ${ids.length} effects in total`);
